para('第 24 题：故意把 parse_packet 里 if (len < 14) 改成 if (len < 10)，编译运行看看会不会出问题。为什么样例数据看不出问题？')
note('答案要点：样例都是完整包，不会触发；但理论上会把 10~13 字节的畸形包放进来，读了越界的 mac/ethertype。这个实验的意义：防御性检查平时「看起来没用」，出事时才显价值。改完记得改回去。')

para('第 25 题（综合）：给项目加一个新协议的支持——ARP。要求：识别 ARP 包，打印出「谁是 IP 的发包者、在找哪个 IP」。（提示：ARP 头在以太网头之后：前 2 字节硬件类型、2 字节协议类型、1+1 字节长度、2 字节操作码、然后 6+4+6+4 字节的地址。先只做「打印一句 ARP 请求/应答」也算完成。）')
