note('答案要点：握手一来一回 + 数据包：54321 出现 3 次（源、目的、源），80 也是 3 次（目的、源、目的）——收发都算的规则。')

para('第 7 题：实时抓包时不写网卡名，程序默认用什么？抓 10 个包怎么写？')
