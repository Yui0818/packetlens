para('这些是 C 基础、网络基础、项目相关、git 四个方向的常见面试题。答案都尽量短——面试要的是「你能用自己的话讲清楚」，不是背课文。')

h2('F.1 C 语言（8 问）')
qa('const 是什么意思？', '「只读」承诺：编译器帮你保证这个变量/指针不改。本项目里所有解析函数的指针参数都是 const——承诺「只读不改别人的数据」。')
qa('static 用在函数上是什么意思？', '「本文件私有」——别的文件看不见、链接时不会撞名字。本项目只有一个文件，用了 static 是为以后拆分做准备，也是好习惯。')
qa('指针和数组什么关系？', '数组名在大多数场景下会「退化」成指向首元素的指针；但数组有长度信息（sizeof 能拿到），指针没有——这就是我们每个函数都要额外传 len 的原因。')
qa('C 语言函数参数是怎么传递的？', '全部按值传递。想「让函数改我的变量」，要传它的地址（指针）——本项目的 PacketInfo *info、FILE *f 都是这个用法。')
qa('位运算都用在哪了？举个例子。', '三个典型：二进制拼字节（rd16 的 << 和 |）、取字段（ihl 的 & 0x0F）、查标志位（TCP 标志的 f & 0x02）。')
qa('malloc 和 free 是干嘛的？这个项目为什么没用？', '动态申请/释放堆内存。本项目所有数据都放栈上或静态区（大小已知），不需要动态内存——也就天然没有内存泄漏问题（第 10.14 节讲过完整的理由）。')
qa('结构体可以直接互相赋值吗？数组呢？', '结构体可以整体赋值（counter_sort 里的交换就用到了）；数组不行，必须逐元素搬（parse_packet 搬 MAC 用的循环）。')
qa('编译警告重要吗？', '重要。本项目坚持「零警告」——我们真修过一个「可能未初始化」的警告（用 {0} 清零），这类警告经常是真 bug 的前兆。')

h2('F.2 网络（8 问）')
qa('TCP 三次握手的过程？', 'SYN → SYN+ACK → ACK。目的：双方都确认「我能发、你能收」且「能收你的」。项目里的包 1、2 就是前两步。')
qa('TCP 和 UDP 的区别？', 'TCP：有连接、可靠、有序、有重传（像打电话）；UDP：无连接、不保证到达（像寄明信片），换来简单快速。')
qa('为什么 DNS 查询用 UDP？', '单次请求响应小、要求快，没有「建立连接」的价值；丢了就再问一次（应用层兜底），比 TCP 握手便宜。')
qa('MAC 地址和 IP 地址有什么区别？', 'MAC 是网卡的物理身份证（链路层、同一局域网内用）；IP 是逻辑门牌号（网络层、跨网络找路用）。数据包的两层头部各写各的。')
qa('ping 是什么原理？', 'ICMP 回显请求（type 8）+ 回显应答（type 0）。它测的是「一个来回的时间」，不建立连接（所以 ping 通不代表端口通）。')
qa('端口的作用？范围？', '区分同一台电脑上的不同程序（大楼的房间号）；0~65535，其中 1024 以下是众所周知的「服务端口」（80、443、53…）。')
qa('大端小端是什么？为什么要关心？', '多字节数字的两种存放顺序。网络协议规定大端，x86 电脑是小端——直接按字节读会读反，必须手工转换（rd16/rd32 的存在意义）。')
qa('ARP 是干嘛的？', '在局域网里「用 IP 找 MAC」：广播问「谁是这个 IP」，持有者回自己的 MAC。以太网类型字段 0x0806（本项目目前只识别、没深入解析）。')

