h2('7.3 标签页区：一排功能入口')

bullet('Code：代码主页面（默认就在这）。看文件、下载代码都在这。')
bullet('Issues：问题与建议区。别人发现 bug 可以在这开一张工单；你也可以给自己记 TODO。个人项目暂时是空的。')
bullet('Pull requests（PR）：别人帮你改代码的合并申请。开源协作的核心流程是：他想改你的项目 → Fork → 改完发 PR 给你 → 你审阅后点合并。个人项目基本用不上，但面试聊到协作流程时得知道它。')
bullet('Actions：自动化流水线，比如每次提交自动帮你跑测试。本项目没配，空的。')
bullet('Projects / Wiki：项目看板 / 项目文档页。小项目用不上。')
bullet('Security / Insights：安全告警 / 数据统计（访问量、贡献者这些）。以后可以点 Insights 看看每天的访问曲线，还挺有意思。')
bullet('Settings：仓库设置，改名、改公开私有、删仓库都在这。只对仓库主人显示。')

