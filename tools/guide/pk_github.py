h2('7.8 提交历史页：全项目最好玩的地方')

para('点文件列表上方的「12 Commits」，数字就是最新提交数，进入提交历史页。这里是项目的时间机器：')
bullet('每一行就是一次提交：一串字母数字（提交的「身份证号」）、一句提交说明（讲这次改了什么）、还有时间。')
bullet('点任意一行，会看到这次提交的「改动报告」也就是 diff：红色行是删掉的，绿色行是新增的。一行行看下去，就是这个项目长胖的全过程，从 v0.1 的九十来行，到现在的七百行。')
bullet('想找某个提交前后代码长啥样：点那个提交，再点 Browse files，就像时光机回到那一刻的完整项目。')
