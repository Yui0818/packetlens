h2('7.8 提交历史页：全项目最好玩的地方')

para('点文件列表上方的「12 Commits」（数字是最新提交数），进入提交历史页。这里是项目的「时间机器」：')
bullet('每一行 = 一次提交：一串字母数字（提交的「身份证号」）、提交说明（一句话讲这次改了什么）、时间。')
bullet('点任意一行，会看到这次提交的「改动报告」（diff）：红色行 = 删掉的内容，绿色行 = 新增的内容。一行行看下去，就是这个项目长胖的全部过程——从 v0.1 的九十来行，到现在的七百行。')
bullet('想找「某个提交前后代码长啥样」：点那个提交 → 点 Browse files，就像时光机回到那个时刻的完整项目。')
note('进阶玩法（暂不必学）：在文件页面点 Blame，能看到每一行代码「是谁、在哪次提交里写的」。你会看到所有行都属于你——因为提交身份设置对了。')

