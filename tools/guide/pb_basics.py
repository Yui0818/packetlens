h2('1.8 git 与 GitHub：代码的「时间机器 + 云端保险柜」')

para('想象你写毕业论文：改到第 17 版，突然发现第 9 版的某段话更好，可惜被你覆盖了……代码写作天天面临同样的问题，于是有了 git。')

bullet('git 是装在你电脑上的「版本控制」工具。每当你敲一条命令提交，也就是 commit，它就给你的代码拍一张「全项目快照」，永久保存，随时能回看、对比、恢复。')
bullet('commit 就是一张快照，还带一句说明，比如「feat: 新增统计功能」，记录这次改了什么、为什么改。')
bullet('GitHub 是网上的「代码托管网站」。把本地 git 的快照 push 到 GitHub，等于给代码在云端上了保险，还顺便有了一个能发给别人看的展示页。')

para('项目的全部历史都完整地存在 GitHub 上，十几次提交、每一版的改动都在。第 7 章你会看到：点开任意一次提交，就能看到那一版改了哪几行，绿色是新增、红色是删除，这就是 git 的「时间机器」界面。')

h2('1.9 抓包：给网络接上一只耳朵')

para('最后回到正题：抓包（packet capture）。')

para('你上网的时候，网络里流淌的是一段一段的「数据包」，也就是 packet。你打开网页、发消息、打游戏，背后都是一串串数据包在收发。抓包就是把这些路过的数据包录下来，留着事后分析。')

bullet('网络管理员用它排查「网为什么慢/断」')
bullet('安全工程师用它分析「有没有攻击、泄露了什么」')
bullet('学生用它来理解网络协议「到底长什么样」，比如你')

para('最有名的抓包工具是 Wireshark，图形界面；还有命令行的 tcpdump。它们背后的核心库就是本项目用的 libpcap。packetlens 相当于「迷你版 tcpdump」：先支持读「录像文件」，再支持「现场直播」实时抓网卡，把包一层层拆解给你看。')

para('最后认识一个文件格式：pcap。抓下来的数据包如果不存起来，关掉窗口就没了。pcap 就是抓包的「录像文件格式」，里面按顺序存着每个包的全套字节和时间戳。项目自带一个示例文件 samples/sample.pcap，一共六个包，还有一个能「凭空造出」这种文件的 Python 脚本。')

