h1('第 1 章  电脑与编程的最基础概念')

para('这一章不讲 packetlens，专门讲「地基」：文件、程序、代码、编译、终端、git……如果你已经懂编程，可以直接跳到第 2 章；完全没接触过的话，这章就是给你准备的。把地基打牢，后面看代码会轻松很多。')

h2('1.1 三个最常用的词：文件、文件夹、路径')

para('打开你的桌面，看到的东西基本都是「文件」和「文件夹」。')

bullet('文件（file）：一块有名字的数据。一张照片、一首歌、一个 Word 文档，都是文件。文件里有内容，内容可以是文字、图片，也可以是电脑能运行的程序。')
bullet('文件夹（folder / 目录 directory）：用来装文件的「盒子」。盒子里面可以放文件，也可以再放盒子（子文件夹），一层套一层。')
bullet('路径（path）：文件在电脑里的「完整地址」，从盘符一路写到文件名。比如本项目的文件夹在 Windows 里的地址是：')

code('D:\\Projects\\packetlens')

para('这一长串的意思逐段拆开看：D: 是硬盘分区（你电脑的 D 盘）→ Projects 是第一层文件夹 → packetlens 是第二层文件夹。反斜杠 \\ 在 Windows 里表示「进入下一层」。')

para('不过在教程里你还会经常看到另一种写法：')
code('/mnt/d/Projects/packetlens')

para('这是同一个文件夹在 WSL 里的地址，WSL 是个 Linux 环境，1.7 节会详细讲。规律很好记：/mnt/d 就是「D 盘」，路径改用正斜杠 / 分层，从根目录开始写。两套写法指的是同一个地方，Windows 的 D:\\Projects\\packetlens 和 WSL 的 /mnt/d/Projects/packetlens 是同一批文件。')

note('小坑预警：Windows 用反斜杠 \\，Linux/WSL 用正斜杠 /。写错方向是新手最常见的错误之一。如果哪天命令报「No such file or directory」，第一件事就是检查斜杠方向和拼写。')

h2('1.2 程序是什么：给电脑的一步一步指令')

para('电脑本身其实非常「笨」。它不会自己理解你想干什么，只会老老实实执行别人写好的、一条一条的指令。所谓「程序」，就是一组指令的集合，像一份菜谱：')

bullet('先干这个，再干那个，如果遇到某种情况就那样处理……')
bullet('菜谱写得越精确，电脑做得越对。一个逗号都不能含糊。')

para('你电脑上的一切——浏览器、微信、游戏——都是程序。程序启动之后，电脑就照着清单干活。packetlens 本身也是一个程序，一份用 C 语言写的指令清单，干的事是读入网络数据包的录像文件，再把里面的内容拆解、打印、统计。')

h2('1.3 源代码与编程语言')

para('写「菜谱」不能用中文大白话直接写，电脑听不懂，得用专门的「编程语言」。人用编程语言写出来的这份菜谱，叫「源代码」，平时简称「代码」。')

para('编程语言有很多种，常见的有 C、Python、Java、JavaScript……可以粗略理解成：不同语言适合不同场合，就像中文、英文、日语各有各的用武之地。本项目里出现了两种语言，分工很清楚：')

bullet('C 语言：写工具本身，也就是 packetlens 这个程序。跑得快、贴近底层，属于「硬核」的那部分。')
bullet('Python：写辅助脚本，生成测试数据、生成文档。写起来轻松，适合干「周边」的活。')

para('项目里有 .c 结尾的 C 文件和 .py 结尾的 Python 文件，看扩展名就能一眼分辨出语言。')

h2('1.4 C 语言：古老、硬核、而且值钱')

para('为什么这个项目选了 C 语言？三个理由：')
bullet('网络世界就是 C 的世界。路由器、操作系统的网络栈、Wireshark 和 tcpdump 这些抓包工具的底层，清一色是 C。想亲手摸摸网络的内部，C 是最直接的路。')
bullet('C 会让你看清电脑真正在干什么。内存、字节、位运算这些概念，在 C 里一个都躲不掉，学一遍够用很久。')
bullet('还有一点比较现实：会用 C 写网络程序的学生不多，简历上算个能打的技能点。')

para('当然，C 也不好惹：没有自动垃圾回收，指针容易出错，编译报错信息有时很抽象。项目的做法是「小步慢走」，每个版本只加一点点功能，而且每行代码都配注释。到第 4 章你会看到，注释比代码还多。')

h2('1.5 编译：把「人看的代码」翻译成「电脑能跑的东西」')

para('C 语言有个重要特点：它不能直接运行，必须先「翻译」。这个过程叫编译（compile）。打个比方：')

bullet('源代码（main.c）= 你写的英文作文稿')
bullet('编译器（gcc）= 翻译官，把作文翻译成电脑母语（机器码）')
bullet('可执行程序（packetlens）= 翻译完成的成品，电脑能直接执行')

para('在实际操作里，你只需要敲一个命令：')
code('make')
para('这个命令会调用叫 gcc 的编译器，把 src/main.c 翻译成名为 packetlens 的可执行文件。make 具体怎么知道该干什么，由项目里的 Makefile 规定，第 5 章会逐行讲解它。')

para('编译时，翻译官还会给你挑毛病：')
bullet('「错误（error）」= 语法问题，翻译失败，必须改。')
bullet('「警告（warning）」= 能翻译，但有些地方「看着不对劲」，建议改。')
note('项目坚持「零警告」：make 的输出里除了编译命令本身，什么都不许有。警告里常常藏着真实的 bug，所以这是个好习惯。第 4 章会讲我们怎么修掉最后一个警告。')

para('另外你会看到编译命令里有个 -lpcap，表示「链接 libpcap 库」。库可以理解成别人写好的工具箱，libpcap 就是「全世界通用的抓包工具箱」，我们的程序借用了它里面现成的函数来读 pcap 文件，不用自己从零造轮子。')

h2('1.6 终端与命令行：程序员的驾驶舱')

para('平时你用鼠标点来点去操作电脑，这叫图形界面，也就是 GUI。程序员还常用另一种方式：终端（terminal），也叫命令行，一个黑底白字的窗口，你在里面打字下命令，电脑执行完把结果打印回来。')

para('为什么不用鼠标？因为编译、运行、git 这些操作用命令描述反而更快更精确，而且能写成脚本自动执行。比如项目里的 push.bat，双击一下就能自动完成推送。')

para('你会用到的命令其实很少，先认识这几个：')
code('cd 文件夹名     进入某个文件夹（change directory）\n'
     'ls              列出当前文件夹里有什么（list）\n'
     'pwd             显示我现在在哪个文件夹（print working directory）\n'
     'make            按 Makefile 的指示编译项目\n'
     './packetlens 参数  运行当前文件夹里的 packetlens 程序，并把参数传给它')

para('最后一条里的 ./ 意思是「当前文件夹里的」。电脑讲究精确：你说 packetlens，它可能去系统里到处找；你说 ./packetlens，它就知道是现在这个文件夹里的那一个。')

para('还有个小符号要说清楚：命令前面的 $ 只是个「提示符」，表示这行是在终端里输入的，别真把 $ 敲进去。')

h2('1.7 WSL：Windows 里住着一个 Linux')

para('项目还有一个关键环境：WSL，全称 Windows Subsystem for Linux，也就是「Windows 里的 Linux 子系统」。简单说，你虽然用 Windows，但电脑里同时住着一个完整的 Linux 系统（Ubuntu），可以和 Windows 一起用。')

para('为什么要请出 Linux？因为抓包工具和 C 编译工具链在 Linux 上最「原汁原味」。libpcap、gcc、make，还有实时抓网卡要用的权限，在 Linux 里都最顺手。Wireshark 的作者当年开发时用的也是这一套。')

para('两个要记住的点：')

bullet('打开方式：开始菜单搜「Ubuntu」或「WSL」，打开的就是 Linux 终端；也可以用 Windows Terminal 里开一个 Ubuntu 标签页。')
bullet('路径互通的规律：Windows 的 D 盘在 WSL 里是 /mnt/d，所以项目的 WSL 地址就是 /mnt/d/Projects/packetlens。在 WSL 里，cd /mnt/d/Projects/packetlens 就能进入项目。')

note('你电脑上的 WSL 已经装好了，是 Ubuntu 24.04，安装过程这里就不再覆盖。如果哪天重装，记得把 WSL 的网络配好，那就是另一个话题了。')

