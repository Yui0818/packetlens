h1('第 2 章  网络基础：数据包的世界')

para('这一章讲「数据包里到底有什么」。不用怕，我们不背概念表——先跟着一次真实上网的故事走一遍，然后拆开每个部件看。读完这章，你就具备了看懂 pcaptool 输出的全部背景知识。')

h2('2.1 先讲故事：点开一个网页，发生了多少事')

para('假设你在浏览器里输入网址、敲下回车。看似一瞬间的事，网络里其实发生了一连串「幕后交易」：')

bullet('第 1 步：问路。浏览器只知道「例子网站」的域名（比如 example.com），但网络里的通信需要 IP 地址。于是它先给 DNS 服务器发一条小消息：「example.com 的 IP 是多少？」这条消息用 UDP 协议发送，走 53 号端口。')
bullet('第 2 步：建立连接。拿到 IP 后，浏览器开始和对方「打招呼」——TCP 的三次握手：我说「我想连接（SYN）」→ 对方说「收到，我也想（SYN+ACK）」→ 我说「好，开始吧（ACK）」。')
bullet('第 3 步：传数据。浏览器把「请给我首页」的请求打包发过去；服务器把网页内容分成一个个数据包发回来。')
bullet('第 4 步：断开。传完了，双方客气地道别，连接关闭。')

para('这整个过程里，所有消息都被打成一串串「数据包」在网络里跑。pcaptool 干的事，就是把这些包拦下来、拆开、告诉你看。本项目自带的示例文件里正好装着上面故事的缩影：两个握手包、一个 UDP 查询包、一个传数据的包，还有一来一回两个 ping 包。')

h2('2.2 分层：网络世界的「套娃」')

para('网络通信有个非常重要的设计思想：分层。可以拿寄快递打比方：')

bullet('你只管把东西装进箱子（应用层：你要做的事，比如发网页请求）')
bullet('快递单上写清楚收件地址、联系电话（传输层：TCP/UDP，管「哪个程序收、怎么可靠地送到」）')
bullet('再套一层外包装，写上中转站信息（网络层：IP，管「从哪个城市到哪个城市」）')
bullet('最后贴面单、交给快递员（链路层：以太网，管「这一站到下一站」）')

para('每一层只管自己负责的事，拆开外包装看到里面还有一层。真正的数据包也是这样一层层「套」出来的：')

code('[以太网头 14 字节][IPv4 头 ≥20 字节][TCP / UDP / ICMP 头][数据]')

para('pcaptool 的解析顺序，就是从最外层往里剥：先看以太网头，再看 IP 头，再看 TCP/UDP/ICMP 头。剥一层，报一层。')

image('tools/assets/d01_encapsulation.png', '图 2-1：一个网络包 = 一层套一层（每层各管各的事）')

h2('2.3 以太网和 MAC 地址：网卡的「身份证」')

para('最外面那层叫以太网（Ethernet），它是局域网（同一个 WiFi / 同一栋楼里的网）通用的规则。以太网包的开头 14 个字节固定是：')

code('目的 MAC 地址（6 字节）| 源 MAC 地址（6 字节）| 类型（2 字节）')

para('MAC 地址是什么？每块网卡出厂时的唯一编号，好比「身份证号」。它长这样：aa:bb:cc:dd:ee:ff——六个字节，用十六进制表示（每个字节两个十六进制字符）。本项目的示例数据里，你的电脑用 00:11:22:33:44:55，对端设备用 aa:bb:cc:dd:ee:ff。')

para('最后的「类型」字段说明「里面装的是什么」：0x0800 表示装了 IPv4 包（最常用），0x0806 是 ARP（局域网内部问「谁是这个 IP？」的包），0x86DD 是 IPv6，以及一些别的。示例文件里六个包的类型全是 IPv4。')

h2('2.4 IP 地址：网络里的「门牌号」')

para('IP 地址负责「跨网络找路」。最常用的是 IPv4 格式：四个 0～255 的数字，用点隔开，比如 192.168.1.109。')
para('几个常识：')
bullet('192.168.x.x、10.x.x.x 这类叫内网地址，是家里/学校局域网内部用的，不能在公网直接出现')
bullet('93.184.216.34 这种就是公网地址（例子里它是 example.com 的 IP）')
bullet('地址在数据包里并不是「点分十进制」的，而是 4 个字节（192.168.1.1 在磁盘上就是 4 个数字 192、168、1、1）。pcaptool 的工作之一，就是把这 4 个字节翻译回人类习惯的写法')

para('IPv4 头（20 字节起步）里对我们最有用的几个字段：')
code('第 0 字节   版本号（4）和首部长度（一般是 20 字节）\n'
     '第 8 字节   TTL：这个包还能被路由器转几次，超了就丢弃\n'
     '第 9 字节   协议号：6 = TCP，17 = UDP，1 = ICMP\n'
     '第 12 字节  源 IP（4 字节）\n'
     '第 16 字节  目的 IP（4 字节）')

para('TTL 有个有趣的历史典故：最初它表示「包能活多少秒」，防止迷路的包永远在网络里转圈；现在实际上变成了「能经过路由器几次」，每过一个路由器减 1，减到 0 就扔。你在输出里看到的 TTL=64 是 Linux 系统的默认值。')

h2('2.5 端口：一栋楼里的「房间号」')

para('IP 地址找到了「哪台电脑」，可一台电脑同时开着浏览器、微信、游戏……数据包该交给哪个程序？这时就需要端口（port）。端口可以理解成楼里的房间号：IP 是大楼地址，端口是房间号。')

para('端口是一个 0～65535 的数字。有两种：')
bullet('服务端口：固定给某种服务用。80 = 网页（HTTP）、443 = 加密网页（HTTPS）、53 = DNS 域名解析、22 = SSH 远程登录')
bullet('临时端口：你电脑发起连接时随机挑一个大号，用完就还。比如示例里的 54321、50000')

para('所以当 pcaptool 打印「源端口=54321 目的端口=80」时，它的意思是：你的电脑（54321 房间）正在和对方的网站服务（80 房间）说话。')

h2('2.6 TCP：像打电话一样通信')

para('TCP 是「可靠传输」的协议，特点：有来有往、有确认、丢包会重发。像打电话——「喂，听得到吗？」「听得到，你说」——确认双方都在线了才开始正题。')

para('建立连接的过程叫三次握手，它的精髓全在 TCP 头的「标志位」（1 个字节里 8 个开关位）：')

bullet('SYN（0x02）：我想建立连接（相当于「喂？」）')
bullet('SYN+ACK（0x12）：我收到你的问候，我也愿意（「听得到，你说」）')
bullet('ACK（0x10）：确认收到。平时传输数据也带着 ACK，表示「上一条我收到了」')
bullet('PSH（0x08）：请尽快把这批数据交给应用程序，别攒着')
bullet('FIN（0x01）：我想挂断；RST（0x04）：异常中断（「啪」地挂电话）')

image('tools/assets/d03_handshake.png', '图 2-2：TCP 三次握手——像打电话前先确认「听得到吗」「听得到」')

para('拿示例数据对照——包 #1 是 54321→80 带着 SYN（你打给网站）；包 #2 是 80→54321 带着 SYN+ACK（网站接起电话）；包 #4 带着 PSH+ACK（双方开始说正事了）。pcaptool 把标志位翻译成 SYN / SYN+ACK / PSH+ACK 这样的文字，就是帮你读懂这段「对话」。')

para('另外 TCP 头里还有个 4 字节的「序列号」（seq），给每个字节编号，保证对方能按顺序拼回原文、发现丢包。')

h2('2.7 UDP：像寄明信片一样通信')

para('UDP 是「尽力而为」的协议：不握手、不确认、不管丢没丢——像寄明信片，贴上邮票扔进邮筒，到不到随缘。它换来的好处是简单、快。')
para('UDP 头只有 8 个字节：源端口、目的端口、长度、校验和。DNS 查询（要快、单次小请求）就用 UDP——示例包 #3 就是一次 DNS 查询（53 → 50000）。')

h2('2.8 ICMP 与 ping：网络里的「信使」')

para('ICMP 不是用来「传数据」的，而是网络设备的「系统消息」：报告错误、探测连通性。你天天用的 ping 命令就是 ICMP 的应用：')

bullet('ping 请求：ICMP 类型 8（回显请求，echo request）——「你在吗？」')
bullet('ping 应答：ICMP 类型 0（回显应答，echo reply）——「我在！」')

para('示例包 #5、#6 正好是一来一回：192.168.1.109 ping 192.168.1.1，对方答了。你在网络里丢包时就会看到「请求超时」——说明请求去了、应答没回，或者压根没到。')

h2('2.9 大端小端：字节序的迷思')

para('一个数字在内存里占多个字节时，就有个问题：先放高位还是先放低位？')

bullet('大端（big-endian）：高位在前。把 0x1234 存成 12 34')
bullet('小端（little-endian）：低位在前。把它存成 34 12')

para('网络协议统一规定：用大端传输，所以大端也叫「网络字节序」。而我们日常用的电脑（x86 芯片）是小端。这意味着：从网络包里直接读出一串字节，不能「抓起来当数字用」，必须手动把字节按大端顺序拼起来——这就是 pcaptool 里 rd16 / rd32 两个小函数存在的全部原因（第 4 章有逐行解释）。')

note('这个坑非常经典：当年很多程序因为字节序处理反了，出现「端口显示成天文数字」之类的 bug。记住口诀：网络是大端，x86 是小端，转换要手动。')

image('tools/assets/d04_endian.png', '图 2-3：同一个数字 0x1234 的两种排法——网络用大端，电脑用小端')

h2('2.10 pcap 文件：抓包「录像」的格式')

para('最后说说本项目要读的文件。pcap 格式非常朴素，就两部分：')

bullet('文件头（24 字节）：说明「这是 pcap 文件、版本、抓包时的链路层是啥（以太网）」')
bullet('数据包们：每个包先来 16 字节的小包头，记「录到它的时刻」和「它有多长」，紧接着就是这个包的原始字节')

para('就这么多。pcaptool 的解析流程因此也是两步：先用 libpcap 把包一个个读出来（读文件这步交给 libpcap，不用我们操心），然后自己动手拆解每个包的字节（这部分是纯手写，也就是第 4 章要讲的核心代码）。')

