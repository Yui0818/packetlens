h2('3.1 一句话认识它')

para('pcaptool 是一个用 C 语言写的命令行网络包分析工具（迷你版 tcpdump / Wireshark）：它能「读抓包录像」或「现场抓网卡」，把每个网络包一层层拆开给你看，还能过滤、统计、导出报告。')

para('它支持两大输入来源、六大功能：')
code('输入来源：① 读 .pcap 录像文件   ② 实时抓网卡（live 模式）\n'
     '功能清单：\n'
     '  1. 逐层解析：以太网 → IPv4 → TCP / UDP / ICMP（含分片判断）\n'
     '  2. 过滤表达式：只显示关心的包（tcp / udp / icmp / port 80 / host IP）\n'
     '  3. 协议统计：每种协议占多少包、多少字节、百分比\n'
     '  4. Top 排名：Talk 最多的 IP、出现最多的端口\n'
     '  5. 实时抓包：监听真实网卡，抓多少个包自己定\n'
     '  6. 导出报告：把分析结果写成文本文件')

