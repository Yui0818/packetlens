h1('第 8 章  常见问题 FAQ（40 问）')

para('这一章收集的都是「不好意思问出口」的小问题。按主题分成五组，随便跳着读就行。')

h2('A 组：关于使用')

qa('命令前面的 ./ 到底是什么意思？',
   '「当前文件夹里的」。电脑找程序时，如果只说名字，它会去系统那几个标准目录里翻；加上 ./ 就是明确告诉它「就用这个文件夹里的那个」。自己编译出来的东西，都得这么写。')
qa('为什么改了代码要重新 make？',
   '你改的是「说明书」（源代码），电脑跑的却是「造好的成品」（可执行文件）。make 就是拿说明书重新翻译一遍成品的过程。不 make，跑的还是旧的那份。')
qa('make clean 是干嘛的？什么时候用？',
   '删掉编译产物，也就是那个 packetlens 文件。一般用不着特意去用；要是编译结果很诡异，或者你想从零验证一遍，make clean && make 重新来一次最干净。')
qa('sudo 是干嘛的？会不会有危险？',
   '以管理员（root）身份执行一次命令，就这一次。危不危险看你拿它干嘛：sudo ./packetlens live 只是抓包，没事；sudo rm -rf / 这种就是把系统删了。原则很简单，知道自己要跑什么再 sudo。网上抄来的命令，先看懂再按回车。')
qa('这东西能抓别人的微信消息吗？',
   '不能，也别试。技术上抓包只能看到「流经你能听到的网段」的流量，何况现在的通信几乎全是加密的，你看到的只是一堆密文；在共享 Wi-Fi 上窃听别人流量，多数场景下是违法的。这工具的正确用法是分析自己的流量、学协议、排查自己家的网络。')
qa('实时抓包为什么抓不到我刚 ping 的流量？',
   '几种常见原因：①抓错网卡了，WSL 里 127.0.0.1 的通信走 lo，你却在听 eth0；②WSL 或虚拟机里，有些内部通信不走普通网卡那条路；③流量发生在你开始抓之前。多试几个网卡名，或者先抓 any 看看有没有包。')
qa('输出太长，怎么存下来慢慢看？',
   '用「重定向」把输出写进文件：./packetlens samples/sample.pcap > 输出.txt。以后所有终端命令都能这么用，> 就是把屏幕输出改道进文件的通用魔法。')
qa('能不能在 Windows 上直接运行 packetlens？',
   '不能直接运行，它靠的是 Linux 那一套（libpcap + Linux 抓包机制）。不过你在 WSL 里跑，就等价于「在 Windows 电脑上用它」，很多人装 WSL 就是图这个。理论上把 libpcap 换成 Windows 版（Npcap）也能移植，那是另一个工程了。')
qa('一次能分析多个 pcap 文件吗？',
   '程序本身一次只读一个文件。想批量处理就上 shell 循环：for f in *.pcap; do ./packetlens "$f"; done。这行会对每个 pcap 跑一遍，属于 shell 技能，以后会学。')
qa('样例文件里的时间戳 1700000000 是什么意思？',
   '这是 Unix 时间，从 1970 年 1 月 1 日开始数的秒数。1700000000 大概对应 2023 年 11 月，这数字一看就是凑的，说明样例数据是人造的。')

h2('B 组：关于代码')

qa('为什么 700 行全都写在一个 main.c 里，不拆成多个文件？',
   '刻意为之。单文件对初学者最友好，打开一个就看到全局。真实项目会拆成模块（多个 .c + .h），等代码再大，或者你想练「多文件工程」了再拆。这是「适合当下的复杂度」，不是偷懒，项目结构本来就该服务读它的人。')
qa('代码里到处出现的 static 是什么意思？',
   '大致就是「这个函数或变量只属于本文件，外面看不见」。好处有俩：不污染全局名字空间；多文件项目里防止重名打架。本项目就一个文件，static 更多是提前演练一下好习惯。')
qa('用这么多全局变量会不会不好？',
   '会有代价：代码一变大，「谁改了它」就难追了。这里是有意的取舍，统计功能天生就全局一份，用全局写最直观。等你想练「更好的工程习惯」，可以把这些装进一个结构体传，当重构练习。')
qa('为什么不用哈希表统计，要用最笨的线性查找？',
   '数据量小的时候（也就几十个 key），线性查找又快又简单，代码还短。哈希表要处理哈希函数、冲突、扩容，拿复杂度换性能，可这里根本不差那点性能。先用最简单的跑起来，需要了再优化，这是很正常的事。')
qa('PacketInfo info = {0}; 里的 {0} 是什么咒语？',
   '「把结构体所有字段初始化为 0」的简写。它保证每个字段一出生就有确定的值，不会读到内存里的旧垃圾。顺带还安抚了编译器，不报警告。')
qa('函数的返回值有 0 有 1 有 2，怎么记住哪个是哪个？',
   '别死记，看约定：本项目里「1 = 成功、0 = 失败」；libpcap 的 pcap_next_ex 是「1 = 有包、0 = 超时、-1 = 出错、-2 = 读完」。这些都在函数上方的注释里写着。读代码先读注释和返回值约定，比背有用。')
qa('指针好难，怎么才能学会？',
   '指针就是一个「存着地址的变量」：普通变量存数字，它存「东西在哪」。学它最好的办法不是啃书，是把本项目里的指针改着玩，把 * 去掉看看报什么错、想想为什么 print_mac 收的是指针而不是数组。用 30 个实验换 3 个小时看书。')
qa('为什么每个解析函数都要带一个 len 参数？',
   '因为 C 的指针只知道「从哪开始」，不知道「有多长」。解析时每一步都得知道「还剩多少字节」，才能安全读字段（第 4 章的边界检查）。这是 C 程序员的日常功课。')
qa('printf 的 %lld、%u、%02x 记不住怎么办？',
   '记三个最常用的就够了：%d/%lld 打十进制整数（lld 用于 long long）、%s 打字符串、%02x 打十六进制。其余现查现用，把格式表存个书签。输错类型最常见的结果是打出天文数字，别慌，改对就行。')
qa('中文注释会不会把程序搞坏？',
   '不会。现代编译器和编辑器默认按 UTF-8 处理中文。唯一的坑是工具太老、或者编码弄错了会出乱码，但那只是「注释变乱」，不影响程序跑。')

h2('C 组：关于工具链')

qa('WSL 和虚拟机（VMware 那种）有什么区别？',
   '虚拟机是「完整模拟一台电脑」，重、慢；WSL 是「Windows 内核里的一个 Linux 兼容层」，轻、快，Linux 和 Windows 文件还互通（D 盘就是 /mnt/d）。日常开发用 WSL 顺畅得多。')
qa('gcc 和 clang 是什么关系？',
   '两个不同的 C 编译器，相当于两个翻译官。gcc 是 GNU 家的，clang 是 LLVM 家的，功能差不多，各有粉丝。本项目用 gcc，Makefile 里 CC = gcc 一行就能换成 clang。')
qa('这个项目里 Python 是干嘛的？C 不是主角吗？',
   'C 是工具本体的主角；Python 干的是外围活儿：造测试数据（make_sample.py）、生成 Word 文档（make_doc.py / make_guide.py）。真实工程里两种语言这么分工很常见，跑得快的活给 C，杂活给脚本语言。')
qa('python-docx 是什么？',
   '一个 Python 库，可以用代码创建和修改 Word 文档。项目里那两份 Word 就是拿它做出来的，想改内容就改脚本再跑一次，不用手工去排版。')
qa('sudo apt install 是什么意思？',
   'apt 是 Ubuntu 的「应用商店命令行版」：sudo apt install 包名 = 以管理员身份装某个软件包。编译本项目的依赖就是这么装的：sudo apt install libpcap-dev。')
qa('git 和 GitHub 到底啥区别，老忘',
   'git 在你自己电脑上，是版本管理工具，管快照；GitHub 在网上，是托管网站，管展示和备份。类比一下：git 是你的相机，commit 是拍照；GitHub 是相册网站，push 是上传。')

h2('D 组：关于 git / GitHub')

qa('「提交」和「推送」的区别？',
   '提交（commit）= 在自己电脑上拍个快照存档；推送（push）= 把存档传到 GitHub。所以会出现「提交了但还没推送」的状态，push.bat 就是帮你把这两步一起做了。')
qa('提交说明写错了/忘了写怎么办？',
   '还没推送的话，git commit --amend -m "新说明" 能改最近一次。已经推送了也问题不大，写错的说明不影响代码，下次注意就行，硬去改历史反而麻烦。')
qa('推送错了想撤销怎么办？',
   '别「删掉重来」。正确姿势是 git revert 那个提交，它会生成一个「反向提交」把改动抵消掉，历史完整、还能查。慌的时候先 git log 看清楚状态再动手。')
qa('「分支」是什么，我需要用吗？',
   '分支 = 仓库的「平行宇宙」，可以在副本上大胆改，成熟了再合并回主线。现在这项目一条 master 主线够用。等你要同时做两个大功能，或者跟别人协作，再学分支工作流。')
qa('GitHub 收费吗？',
   '个人用免费：公开仓库不限量，私有仓库也有免费额度。你的账号现在完全够用，一分钱不用花。')
qa('仓库能改回私有吗？',
   '能。仓库页 Settings → General → 最下方 Danger Zone → Change visibility。做简历项目建议保持公开。')
qa('别人能看到我的邮箱吗？',
   '看不到。提交里用的是 GitHub 给的隐私邮箱（324952380+Yui0818@users.noreply.github.com 这种），不是你的真实邮箱。大家都这么干，push.bat 里已经帮你设好了。')
qa('Word 文档传到 GitHub 合适吗？',
   '可以，但不适合存「很大的」二进制文件，因为每次改动都会存一份完整副本，越积越大。本项目文档就几十 KB，完全没问题。几 MB 以上就该换个方式了，比如放到 Releases 附件里。')

