h1('第 8 章  常见问题 FAQ（40 问）')

para('这一章收集了「不好意思问出口」的各种小问题。按主题分成五组，随便跳读。')

h2('A 组：关于使用')

qa('命令前面的 ./ 到底是什么意思？',
   '「当前文件夹里的」。电脑找程序时如果只说名字，会去系统的标准目录里找；加上 ./ 就是明确告诉它「就用这个文件夹里的那个」。自己编译出来的程序都必须这么写。')
qa('为什么改了代码要重新 make？',
   '你改的是「说明书」（源代码），电脑跑的是「造好的成品」（可执行文件）。make 就是把说明书重新翻译成成品的过程。不 make，跑的还是旧成品。')
qa('make clean 是干嘛的？什么时候用？',
   '删掉编译产物（packetlens 文件）。一般不用特意用；当编译结果诡异、或想从零验证一遍时，make clean && make 重新来过最干净。')
qa('sudo 是干嘛的？会不会有危险？',
   'sudo = 以管理员（root）身份执行一次命令。危险与否取决于你执行什么：sudo ./packetlens live 只是抓包，没问题；但 sudo rm -rf / 这种会删系统。原则：知道自己要跑什么再 sudo，网上抄来的命令先看懂再按回车。')
qa('这东西能抓别人的微信消息吗？',
   '不能，也别试。技术上，抓包只能看到「流经你能听到的网段」的流量，而且现在的通信几乎全是加密的（你看到的只是密文）；在共享 Wi-Fi 上窃听他人流量在多数场景下是违法行为。这个工具正确的用法是分析自己的流量、学习协议、排查自己的网络问题。')
qa('实时抓包为什么抓不到我刚 ping 的流量？',
   '几种常见原因：①抓错网卡了（WSL 里的 127.0.0.1 通信走 lo，你却在听 eth0）；②在 WSL/虚拟机环境里，某些内部通信不走普通网卡路径；③流量发生在你开始抓之前。多试几个网卡名，或先抓 any 看看有没有包。')
qa('输出太长，怎么存下来慢慢看？',
   '用「重定向」把输出写进文件：./packetlens samples/sample.pcap > 输出.txt——以后所有终端命令都能这么用，> 是「把屏幕输出改道进文件」的通用魔法。')
qa('能不能在 Windows 上直接运行 packetlens？',
   '不能直接运行——它用了 Linux 的世界（libpcap + Linux 抓包机制）。但你在 WSL 里运行就等价于「在 Windows 电脑上用它」，这就是 WSL 的意义。理论上把 libpcap 换成 Windows 版（Npcap）也能移植，那是另一个工程。')
qa('一次能分析多个 pcap 文件吗？',
   '程序本身一次读一个文件。想批量处理，用 shell 循环：for f in *.pcap; do ./packetlens "$f"; done——这行命令会对每个 pcap 跑一遍（这属于 shell 技能，以后学）。')
qa('样例文件里的时间戳 1700000000 是什么意思？',
   '这是「Unix 时间」——从 1970 年 1 月 1 日开始的秒数。1700000000 换算过来大约是 2023 年 11 月——一个「凑整好看」的假时间，代表样例是人造数据。')

h2('B 组：关于代码')

qa('为什么 700 行全都写在一个 main.c 里，不拆成多个文件？',
   '刻意为之：单文件对初学者最友好，打开一个文件就看到全局。真实项目会拆成模块（多个 .c + .h），等代码再大、或你想练习「多文件工程」时再拆。这是「适合当下的复杂度」，不是偷懒——项目结构应该服务读者。')
qa('代码里到处出现的 static 是什么意思？',
   '大致可以理解为「这个函数/变量只属于本文件，外面看不见」。好处：一是不污染全局名字空间，二是在多文件项目里防止重名打架。本项目只有一个文件，static 更多是好习惯的提前演练。')
qa('用这么多全局变量会不会不好？',
   '会有代价：代码变大后「谁改了它」难追踪。这里是有意的取舍——统计功能天生是全局一份，用全局最直观。等你想练「更好的工程习惯」时，可以把这些装进一个结构体传递（重构练习）。')
qa('为什么不用哈希表统计，要用最笨的线性查找？',
   '数据量小（几十个 key）时，线性查找又快又简单，代码还短。哈希表要处理哈希函数、冲突、扩容——复杂度换性能，而这里不差那点性能。「先用简单方案跑起来，有需要再优化」是正常的工程节奏。')
qa('PacketInfo info = {0}; 里的 {0} 是什么咒语？',
   '「把结构体所有字段初始化为 0」的简写。它保证每个字段出生就有确定的值，避免「读到内存里的旧垃圾」。顺带还安抚了编译器（不报警告）。')
qa('函数的返回值有 0 有 1 有 2，怎么记住哪个是哪个？',
   '别死记，看约定：本项目里「1 = 成功、0 = 失败」；libpcap 的 pcap_next_ex 是「1 = 有包、0 = 超时、-1 = 出错、-2 = 读完」——这些都在函数上方注释里写着。读代码先读注释和返回值约定，比背重要。')
qa('指针好难，怎么才能学会？',
   '指针就是一个「存着地址的变量」：普通变量存数字，指针存「东西在哪」。学它的最好办法不是看书，是把本项目里的指针改着玩：把 * 去掉看看报什么错、想想为什么 print_mac 收的是指针而不是数组。用 30 个实验换 3 个小时看书。')
qa('为什么每个解析函数都要带一个 len 参数？',
   '因为 C 的指针只知道「从哪开始」，不知道「有多长」。解析时每一步都要知道「还剩多少字节」，才能安全地读取字段（第 4 章的边界检查）。这是 C 程序员的日常功课。')
qa('printf 的 %lld、%u、%02x 记不住怎么办？',
   '记三个最常用的就够：%d/%lld 打十进制整数（lld 用于 long long）、%s 打字符串、%02x 打十六进制。其余现查现用（把格式表存个书签）。输错类型最常见的结果是打出天文数字，别慌，改对就行。')
qa('中文注释会不会把程序搞坏？',
   '不会。现代编译器和编辑器默认都用 UTF-8 处理中文。唯一的坑是很老的工具或错误编码时出现乱码——但那只会让「注释变乱」，不影响程序运行。')

h2('C 组：关于工具链')

qa('WSL 和虚拟机（VMware 那种）有什么区别？',
   '虚拟机是「完整模拟一台电脑」，重、慢；WSL 是「Windows 内核里的一个 Linux 兼容层」，轻、快，Linux 和 Windows 文件互通（D 盘就是 /mnt/d）。日常开发用 WSL 体验顺畅得多。')
qa('gcc 和 clang 是什么关系？',
   '两个不同的 C 编译器（翻译官），gcc 是 GNU 家的，clang 是 LLVM 家的，功能类似、各有粉丝。本项目用 gcc（Makefile 里 CC = gcc 一行就能换成 clang）。')
qa('这个项目里 Python 是干嘛的？C 不是主角吗？',
   'C 是工具本体的主角；Python 干「周边活儿」——造测试数据（make_sample.py）、生成文档（make_doc.py / make_guide.py）。两种语言分工是真实工程的常态：跑得快的活给 C，干杂活的活给「脚本语言」。')
qa('python-docx 是什么？',
   '一个 Python 库，能用代码创建和修改 Word 文档。本项目的两份 Word 都是它生成的——所以「文档」也是可复现、可随时重造的，不是手工排出来的。')
qa('sudo apt install 是什么意思？',
   'apt 是 Ubuntu 的「应用商店命令行版」：sudo apt install 包名 = 以管理员身份安装某个软件包。编译本项目的依赖就是这么装的：sudo apt install libpcap-dev。')
qa('git 和 GitHub 到底啥区别，老忘',
   'git 在你自己电脑上（版本管理工具，管快照）；GitHub 在网上（托管网站，管展示和备份）。类比：git 是你的相机，commit 是拍照；GitHub 是相册网站，push 是上传。')

h2('D 组：关于 git / GitHub')

qa('「提交」和「推送」的区别？',
   '提交（commit）= 在自己电脑上拍个快照存档；推送（push）= 把存档上传到 GitHub。所以可以「提交了但还没推送」——push.bat 帮你把两步连起来做。')
qa('提交说明写错了/忘了写怎么办？',
   '还没推送的话：git commit --amend -m "新说明" 可以改最近一次。已经推送了也问题不大——写错的说明不影响代码，下次注意即可（强行改历史反而麻烦）。')
qa('推送错了想撤销怎么办？',
   '不要「删掉重来」。正确姿势：git revert 那个提交——它会生成一个「反向提交」把改动抵消掉，历史完整可查。慌的时候先 git log 看清楚状态再动手。')
qa('「分支」是什么，我需要用吗？',
   '分支 = 仓库的「平行宇宙」，可以在副本上大胆改，成熟了再合并回主线。现在的项目一条 master 主线足够用。等你要同时做两个大功能、或与别人协作时，再学分支工作流。')
qa('GitHub 收费吗？',
   '个人用免费：公开仓库无限量，私有仓库也有免费额度。你的账号现在完全够用，不用花一分钱。')
qa('仓库能改回私有吗？',
   '能。仓库页 Settings → General → 最下方 Danger Zone → Change visibility。做简历项目建议保持公开。')
qa('别人能看到我的邮箱吗？',
   '看不到。提交里用的是 GitHub 提供的隐私邮箱（324952380+Yui0818@users.noreply.github.com 这种），不是你的真实邮箱——这是 standard practice，push.bat 里已经帮你设好了。')
qa('Word 文档传到 GitHub 合适吗？',
   '可以，但不适合存「很大的」二进制文件（每次改动都会存一份完整副本，越积越大）。本项目文档几十 KB，完全没问题。几 MB 以上就该换方式（比如 Releases 附件）。')

