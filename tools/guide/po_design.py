"""第 10 章：设计决策集，为什么这么写。"""

from docbuild import *

h1('第 10 章  设计决策集：为什么这么写')

para('走到这一步，代码你基本都读得懂了。但读得懂和讲得清之间还差着一层：面试官和老师最爱问的，往往不是「这行代码是什么」，而是「为什么这么写、为什么不那么写」。下面把项目里 15 个真实的设计选择一个个摊开。每个都有权衡，也都没什么标准答案，只是我们当初选这条路的理由。')
para('把这一章当「答辩预演」来读：每一节就是一个可能被问到的问题。')

h2('10.1 为什么全部写在一个 main.c 里，不拆成十几个文件？')
para('专业项目通常按模块拆文件，parse.c、print.c、stats.c 各管一摊，多人协作不会互相踩。我们偏偏没这么干，原因很简单：**这个项目的第一读者是你自己**，还有那些想读懂它的人。')
bullet('单文件 = 打开一个文件，从上到下就是程序的完整故事，不用在十几个文件之间跳。')
bullet('教学场景里，找得到比架构漂亮更重要。等你写第二个项目，或者这个项目超过两千行，再拆也不迟。那时候你会自己生出拆的动力，而不是为了拆而拆。')
para('这条经验可以总结成一句话：架构要匹配当下的复杂度，超前设计也是债。')

h2('10.2 为什么手工拼字节（rd16/rd32），不用结构体强转？')
para('读网络头最「快」的写法是定义个结构体，把包的指针一转型，字段就像长在包上一样：')
code('struct iphdr *ip = (struct iphdr *)p;   /* 看起来很方便，但是坑 */\nip->saddr …')
para('为什么我们不这么干？三个坑：')
bullet('字节序：结构体字段读出来是主机序，网络数据是大端，在 x86 上直接读会读反，还得再转一次，白绕一圈。')
bullet('内存对齐：结构体会按对齐规则垫字节，可网络头的字段是紧紧挤在一起的，结构体布局未必对得上真实字节，编译器还可能在中间插 padding。')
bullet('可移植性：不同平台的对齐规则不同，同一份代码在不同机器上可能读出不同的结果。')
para('所以最终选了最「笨」也最稳的做法：p[0]、p[1] 一个字节一个字节地取，用 << 和 | 按大端拼。慢一点？读几十个字节的差异可以忽略。稳，才是网络编程的第一原则。')

h2('10.3 为什么要有 PacketInfo「档案袋」？')
para('v0.2 的写法是边解析边打印，解析到哪一层就把哪一层打出来。到 v0.3 要加统计，问题就来了：统计也要用到解析出的 IP、协议、端口，难道再解析一遍？')
bullet('再解析一遍 = 同一套解析逻辑写两处，改一处忘一处，必出 bug。')
bullet('于是改成「先解析进结构体，谁需要谁来读」：打印来读、统计来读、过滤来读。一次解析，三方使用。')
para('其实这是个挺通用的套路：数据先归拢成一份结构化的中间产物，各个功能都面向它干活，谁也别再直接去看原始字节。以后你想加导出 CSV、按会话聚合，无非再多写一个「读档案袋的人」。')

h2('10.4 为什么用 has_ipv4、has_ports 这种「开关字段」？')
para('解析是有可能半途而废的：包被截断了、根本不是 IPv4、遇到分片只剩后续片……这种时候 ip_src、sport 这些字段就是没有意义的数。那怎么表达「有」还是「没有」？')
bullet('方案一：拿个特殊值表示「没有」，比如 IP 全 0。可 0.0.0.0 本身是合法地址，这么干会误伤。')
bullet('方案二：加一个专门的开关字段，1 = 这组数据有效。我们选了这个。')
para('「开关 + 数据」是解析类程序的经典组合，你在任何解析器代码里都能见到它的变体。判断数据前先看开关，这个习惯能挡掉一大类「读垃圾数据」的 bug。')

h2('10.5 为什么每一层都要做边界检查？')
para('每次读字段前都问一句「剩下的字节够吗」，会让代码变长、变「丑」。为什么不省掉？')
bullet('因为输入不可信：文件可能损坏，包可能被截断（真实抓包里这种情况很常见），更别说有人专门构造恶意数据冲你来。一旦读到缓冲区外面，轻则读到垃圾，重则程序崩溃甚至被人利用。')
bullet('边界检查的成本是一行 if，收益是「永远不会因为一个畸形包而崩」。这笔账在任何系统里都是赚的。')
para('这个原则有个名字，叫先验后用（validate before use）。它不止适用于网络编程，凡是处理外部输入的程序都该这么干。')

h2('10.6 为什么统计用一堆全局变量？什么时候不该这么干？')
para('统计变量 total、tcp_pkts、ip_table 这些全都是全局的，函数直接读写。好处很明显：不用在十几个函数签名里传来传去。')
para('代价也要说清楚：')
bullet('谁改的它？读代码时得满文件去找修改点。大型项目里管这叫「全局状态地狱」。')
bullet('没法同时跑两份统计，比如并行处理两个文件时就会打架，因为它们共用同一份全局变量。')
para('什么时候该动它？当项目出现「多实例」的需求，或者代码大到一个人记不住所有全局名了，就把它们装进一个 Stats 结构体，谁用谁传。小项目图省事，大项目图清爽，说到底还是那句话：匹配当下的复杂度。')

h2('10.7 为什么用「数组 + 线性查找」做计数器，不用哈希表？')
para('哈希表查找是 O(1)，线性查找是 O(n)，听起来哈希完胜。但对这个场景：')
bullet('样例数据只有个位数的 key，n 极小，「O(n) 的 n」等于 4、5，和 O(1) 没有可感知的区别。')
bullet('哈希表得自己写哈希函数、处理冲突、还要考虑扩容，几十行代码换来一个你根本用不上的性能。')
bullet('线性查找的表还能「原样打印」，调试时一眼看穿。')
para('性能优化有条铁律：先测量，再优化。没有测量数据撑腰的「优化」，多半只是给 bug 多开了几个入口。等哪天真要处理百万级流量了，再换数据结构也不迟，到那时它才配叫「性能优化」。')

h2('10.8 为什么排序用最「笨」的选择排序？')
para('道理和上一条一样：数据量决定用什么武器。Top 榜撑死几十行，选择排序的 O(n²) 在 n=20 时也就 400 次比较——快得感觉不到。代码才九行，逻辑就是每轮挑最大的，连注释都省了。')
para('还有个附带的好处：这段简单排序你能徒手复述出来。面试紧张的时候，在白板上把选择排序写对，比背一个标准库函数调用有用得多。')

h2('10.9 为什么百分比要写成 100.0 * a / b，不能写 100 * a / b？')
para('这个坑前面反复出现过，这里单独拎出来当成一个「决策」讲：C 语言的整数除法会把小数直接砍掉。')
code('100 * 209 / 436   → 47      （对，连 0.9 都被砍了）\n100.0 * 209 / 436 → 47.9    （100.0 让整个式子是小数运算）')
para('再往深想一层：C 语言里「整数 / 整数」的结果类型就是整数，这是语言规则，不是 bug。写上 100.0 就等于告诉编译器「这次我要小数」。Python 3、JS 这些语言默认就是小数除法，所以从别的语言转过来的人最容易在这儿翻车。')

h2('10.10 为什么函数返回值有的用 0 有的用 1，还有 -1、-2？')
para('这是「约定」的问题，而约定因「谁定的」而不同：')
bullet('我们自己写的函数：1 = 成功、0 = 失败，parse_packet、parse_filter_args、filter_match 都是这个约定。')
bullet('libpcap 的 pcap_next_ex 就不一样：1 = 有包、0 = 超时、-1 = 出错、-2 = 读完，这是库作者定的规矩，我们只能照着来。')
para('这点在面试里能加分：**读代码的第一件事是读约定**。函数头上的注释、返回值说明，往往比代码本身更早决定你该怎么用它。养成先看约定、再看实现的顺序，能少踩很多坑。')

h2('10.11 为什么两种模式（读文件 / 抓网卡）共用 handle_packet？')
para('加 live 模式的时候，本来可以把读文件的主循环复制一份改改交差，这写法最快也最危险：')
bullet('复制出来的两份逻辑，以后修 bug 要记得修两处，忘一处就是「有的模式好了、有的模式还坏着」的玄学 bug。')
bullet('于是把「处理一个包」抽成 handle_packet：编号、解析、过滤、打印、统计，一套逻辑两边用。')
para('这就是 DRY 原则（Don\'t Repeat Yourself）。加 live 模式时，原来读文件的逻辑几乎一行没动，抽象得好就是这个回报。')

h2('10.12 为什么统计输出要写成 emit_stats(FILE *out)，而不是直接用 printf？')
para('v0.6 要支持「把统计写进报告文件」。最偷懒的做法是把打印统计的代码复制一份，把 printf 全改成 fprintf(f, ...)。')
bullet('我们没复制，而是把函数的第一个参数改成 FILE *out，让「写去哪」由调用者说了算：传 stdout 就是屏幕，传文件指针就是文件。')
para('函数内部的逻辑一行没改，却同时支持了两个目的地。这算是「面向抽象编程」最小的一个例子：把会变的部分（写去哪）变成参数，把不变的部分（统计逻辑）留一份就行。')

h2('10.13 为什么过滤器的「不限」用 0，而 host 却要额外一个开关？')
para('看似不统一，其实分别有理由：')
bullet('协议号 0 和端口 0 现实中都不存在，协议号从 1 开始，端口也从 1 起常用，所以 0 是个安全的「没人用」的值，可以拿来当哨兵（sentinel）。')
bullet('可 0.0.0.0 是个真实存在的地址，代表「本机 / 任意」，拿全 0 当「没设置」会产生歧义，所以 host 得额外配一个 has_host 开关，明确用户到底设没设。')
para('这条的考点是「哨兵值要选值域外的值」。选一个现实里可能出现的值当哨兵，就是给未来埋雷。')

h2('10.14 为什么整个程序没有一次 malloc（动态分配内存）？')
para('「C 语言项目居然没用 malloc？」没错，这是刻意的：')
bullet('所有数据都放在栈上或静态区：PacketInfo 是局部变量、计数表是静态数组。内存随程序结束自动回收，零泄漏、零野指针。')
bullet('教学项目里，malloc/free 那套坑（漏 free、double free、free 之后又去用）会把注意力从网络解析上带偏。')
para('那什么时候该学 malloc？当你需要一份「运行前才知道多大」的数据时，比如包的数量事先未知、又要把所有包都存下来。那是进阶课的一整章。学的时候记住一点：手动内存管理这件事你只是往后推了推，并没有绕过去。')

h2('10.15 为什么手写 Makefile，不用 CMake？')
para('CMake 能处理「多平台、多目录、多依赖」的大型构建，是现代 C 项目的标配。但：')
bullet('本项目的构建无非是 gcc 编一个文件、再链一个库，一行命令的事，上 CMake 配置文件反而更长。')
bullet('Makefile 短短 30 行，把「编译是怎么发生的」原原本本展示出来。看懂它之后，你再去学 CMake，会觉得「原来它自动化的是这些事」。')
bullet('工具的选择永远是：先用能让你看清原理的那一个，再用能让你省力的那一个。')

para('15 个决策讲完了。回头看，它们背后翻来覆去就是这么几句：匹配当下的复杂度、先验后用、一次解析多方使用、把会变的参数化、先用简单方案跑起来。以后你在别的项目里还会一次次撞上它们，所谓「经验」，说白了就是这些。')
