"""第 10 章：设计决策集——为什么这么写。"""

from docbuild import *

h1('第 10 章  设计决策集：为什么这么写')

para('走到这一步，你已经能读懂所有代码了。但「读懂」和「会讲」之间还差一层：面试官和老师最爱问的不是「这行是什么」，而是「为什么这么写、为什么不那样写」。这一章把项目里 15 个真实的设计决定逐个摊开——每个决定都有权衡，没有标准答案，但我们选的那条路都有理由。')
para('把这一章当「答辩预演」来读：每一节就是一个可能被问到的问题。')

h2('10.1 为什么全部写在一个 main.c 里，不拆成十几个文件？')
para('专业项目通常按模块拆文件：parse.c、print.c、stats.c……好处是各管一摊、多人协作不打架。我们反其道而行，理由是：**这个项目的第一读者是你自己（和想学会它的人）**。')
bullet('单文件 = 打开一个文件，从上到下就是程序的完整故事，不用在十几个文件之间跳。')
bullet('教学场景里，「找得到」比「架构漂亮」更重要。等你写第二个项目、或者这个项目超过两千行时，再拆不迟——那时你会真正感受到拆的动力，而不是为了拆而拆。')
para('这条经验可以总结成一句话：架构要匹配当下的复杂度，超前设计也是债。')

h2('10.2 为什么手工拼字节（rd16/rd32），不用结构体强转？')
para('读网络头最「快」的写法是定义个结构体，把包的指针一转型，字段就像长在包上一样：')
code('struct iphdr *ip = (struct iphdr *)p;   /* 看起来很方便，但是坑 */\nip->saddr …')
para('为什么我们不这么干？三个坑：')
bullet('字节序：结构体字段读出来是「主机序」，网络数据是「大端」——在 x86 上会读反，还得再转一次，绕。')
bullet('内存对齐：结构体会按对齐规则「垫字节」，而网络头的字段是紧挤着的，结构体的布局未必和真实字节一致（编译器可能有 padding）。')
bullet('可移植性：不同平台的对齐规则不同，同一份代码在不同机器上可能读出不同的结果。')
para('所以最终选了最「笨」也最稳的做法：p[0]、p[1] 一个字节一个字节地取，用 << 和 | 按大端拼。慢一点？读几十个字节的差异可以忽略。稳，才是网络编程的第一原则。')

h2('10.3 为什么要有 PacketInfo「档案袋」？')
para('v0.2 的写法是「边解析边打印」——解析到哪层就打印哪层。到了 v0.3 要加统计，问题来了：统计也需要解析出的 IP、协议、端口，难道再解析一遍？')
bullet('再解析一遍 = 同一套解析逻辑写两处，改一处忘一处，必出 bug。')
bullet('于是改成「先解析进结构体，谁需要谁来读」：打印来读、统计来读、过滤来读。一次解析，三方使用。')
para('这其实是一个通用的中台模式：数据先归拢成「结构化的中间产物」，各种功能都面向中间产物干活，而不是面向原始字节。以后你想加「导出 CSV」「按会话聚合」，都只需要多写一个「读档案袋的人」。')

h2('10.4 为什么用 has_ipv4、has_ports 这种「开关字段」？')
para('解析是有可能「半途而废」的：包被截断了、不是 IPv4、遇到分片后续片……这时候 ip_src、sport 这些字段就是「没有意义的数」。怎么表达「有 or 没有」？')
bullet('方案一：用特殊值表示「没有」（比如 IP 全 0）。但 0.0.0.0 是合法地址，会误伤。')
bullet('方案二：加一个专门的开关字段，1 = 这组数据有效。我们选了这个。')
para('「开关 + 数据」是解析类程序的经典组合，你在任何解析器代码里都能见到它的变体。判断数据前先看开关，这个习惯能挡掉一大类「读垃圾数据」的 bug。')

h2('10.5 为什么每一层都要做边界检查？')
para('每次读字段前都问一句「剩下的字节够吗」，会让代码变长、变「丑」。为什么不省掉？')
bullet('因为输入是不可信的：文件可能损坏、包可能被截断（真实抓包里很常见）、恶意构造的数据更是专门冲着你来的。读到缓冲区外面的内存，轻则读到垃圾、重则程序崩溃甚至被利用。')
bullet('边界检查的成本是一行 if，收益是「永远不会因为一个畸形包而崩」。这笔账在任何系统里都是赚的。')
para('记住这个原则的名字：先验后用（validate before use）。它不只适用于网络编程——所有处理外部输入的程序都该这样。')

h2('10.6 为什么统计用一堆全局变量？什么时候不该这么干？')
para('统计变量（total、tcp_pkts、ip_table……）全部是全局的，所有函数直接读写。好处显而易见：不用在十几个函数签名里传来传去。')
para('代价也要说清楚：')
bullet('谁改了它？——读代码时要满文件找修改点（大型项目里这叫「全局状态地狱」）。')
bullet('不能同时跑两份统计（比如并行处理两个文件），因为它们共用同一份全局。')
para('什么时候该改？当项目出现「多实例」需求、或代码大到一个人记不住所有全局名时，就把它们装进一个 Stats 结构体，谁用谁传。小项目图直接，大项目图清晰——这也是「匹配当下复杂度」。')

h2('10.7 为什么用「数组 + 线性查找」做计数器，不用哈希表？')
para('哈希表查找是 O(1)，线性查找是 O(n)，听起来哈希完胜。但对这个场景：')
bullet('样例数据只有个位数的 key，n 极小，「O(n) 的 n」等于 4、5，和 O(1) 没有可感知的区别。')
bullet('哈希表要写哈希函数、处理冲突、考虑扩容——几十行代码换来一个你用不上的性能。')
bullet('线性查找的表还能「原样打印」，调试时一眼看穿。')
para('工程里的性能优化有一条铁律：先测量，再优化。没有测量数据的「优化」，往往只是给 bug 增加入口。等哪天真的处理百万级流量，再换数据结构，那时它有明确的名字：性能优化阶段。')

h2('10.8 为什么排序用最「笨」的选择排序？')
para('和上一条同源：数据量决定武器。Top 榜最多几十行，选择排序的 O(n²) 在 n=20 时是 400 次比较——电光石火。而它的代码只有九行，逻辑「每轮挑最大的」，连注释都不需要。')
para('这里有个隐藏的收益：这份简单排序是「可以徒手复述」的。面试紧张时，能白板写对选择排序的人，比背一个标准库调用的人更能说明问题。')

h2('10.9 为什么百分比要写成 100.0 * a / b，不能写 100 * a / b？')
para('这是全书反复出现的一个坑，值得单独成一个「决策」：C 语言的整数除法会把小数砍掉。')
code('100 * 209 / 436   → 47      （对，连 0.9 都被砍了）\n100.0 * 209 / 436 → 47.9    （100.0 让整个式子是小数运算）')
para('深一层理解：C 语言里「整数 / 整数」的结果类型就是整数，这是语言规则，不是 bug。写 100.0 等于告诉编译器「这次我要小数」。其他语言（Python 3、JS）默认就是小数除法，所以从别的语言转过来的人最容易在这里翻车。')

h2('10.10 为什么函数返回值有的用 0 有的用 1，还有 -1、-2？')
para('这是「约定」的问题，而约定因「谁定的」而不同：')
bullet('我们自己的函数：1 = 成功、0 = 失败（parse_packet、parse_filter_args、filter_match 都是这个约定）。')
bullet('libpcap 的 pcap_next_ex：「1 = 有包、0 = 超时、-1 = 出错、-2 = 读完」——这是库作者定的，我们只能遵守。')
para('面试加分点：**读代码的第一件事是读约定**。每个函数头上的注释、以及返回值说明，比代码本身更先决定你怎么用它。养成先读约定、再看实现的顺序，能少踩非常多的坑。')

h2('10.11 为什么两种模式（读文件 / 抓网卡）共用 handle_packet？')
para('加 live 模式时本来可以复制一份读文件的主循环，改改就行——这是最快、也最危险的写法：')
bullet('复制出来的两份逻辑，以后修 bug 要记得修两处，忘一处就是「有的模式好了、有的模式还坏着」的玄学 bug。')
bullet('于是把「处理一个包」抽成 handle_packet：编号、解析、过滤、打印、统计，一套逻辑两边用。')
para('这叫 DRY 原则（Don\'t Repeat Yourself）。加 live 模式时，旧的读文件逻辑几乎一行没动——这就是好抽象的回报。')

h2('10.12 为什么统计输出要写成 emit_stats(FILE *out)，而不是直接用 printf？')
para('v0.6 要支持「把统计写进报告文件」。最偷懒的做法是把打印统计的代码复制一份，把 printf 全改成 fprintf(f, ...)。')
bullet('我们没复制：把函数的第一个参数改成 FILE *out，让「写去哪」变成调用者的选择——传 stdout 就是屏幕，传文件指针就是文件。')
para('函数内部逻辑一行没变，却同时支持了两个目的地。这是「面向抽象编程」的最小示例：把「变化的部分」（写去哪）参数化，把「不变的部分」（统计逻辑）留一份。')

h2('10.13 为什么过滤器的「不限」用 0，而 host 却要额外一个开关？')
para('看似不统一，其实分别有理由：')
bullet('协议号 0 和端口 0 在现实中不存在（协议号从 1 开始、端口从 1 起常用），所以 0 是安全的「没人用」值，可以当哨兵（sentinel）。')
bullet('而 0.0.0.0 是一个真实存在的地址（表示「本机/任意」），拿全 0 当「没设置」会有歧义——所以 host 需要一个 has_host 开关来明确「用户到底设没设」。')
para('这条的考点是「哨兵值要选值域外的值」。选一个现实里可能出现的值当哨兵，就是给未来埋雷。')

h2('10.14 为什么整个程序没有一次 malloc（动态分配内存）？')
para('「C 语言项目居然没用 malloc？」——是的，这是刻意的：')
bullet('所有数据都放在栈上或静态区：PacketInfo 是局部变量、计数表是静态数组。内存随程序结束自动回收，零泄漏、零野指针。')
bullet('教学项目里，malloc/free 的一套坑（漏 free、double free、free 后使用）会把注意力从「网络解析」带偏。')
para('什么时候该学 malloc？当你需要「运行前才知道多大」的数据时（比如包数量事先未知、要存所有包）。那是进阶课的一整章——学的时候，记得你把「手动内存管理」这件事已经推迟了一次，而不是绕过了它。')

h2('10.15 为什么手写 Makefile，不用 CMake？')
para('CMake 能处理「多平台、多目录、多依赖」的大型构建，是现代 C 项目的标配。但：')
bullet('本项目的构建就是「gcc 一个文件 + 链一个库」——一行命令的事，CMake 的配置文件反而更长。')
bullet('Makefile 短短 30 行，把「编译是怎么发生的」原原本本展示出来。看懂它之后，你再去学 CMake，会觉得「原来它自动化的是这些事」。')
bullet('工具的选择永远是：先用能让你看清原理的那一个，再用能让你省力的那一个。')

para('15 个决策讲完了。回头看，它们背后其实是同几句话：匹配当下复杂度、先验后用、一次解析多方使用、把变化参数化、简单方案先跑起来。这些话你在别的项目里还会反复遇到——这就是「经验」这个词的实体。')
